import fs from 'fs';
import path from 'path';
import type { FeatureMetaSnapshot } from '../../../lib/dist/index.js';
import type { CatalogParamDef } from '../part-catalog/scan.ts';
import type { LengthUnit } from '../project-config.ts';
import { PackageName } from './package-name.ts';

/** One feature builder a package exports, as its manifest snapshots it. */
export type PackageManifestFeature = {
  /**
   * The feature's plain id (`gear`), as its class declares it. An installed
   * package's features are keyed by the package at load time
   * (`@acme/gears:gear`, `FeatureKey`); the manifest never holds a key.
   */
  id: string;
  /** The name `index.js` re-exports the builder by. */
  exportName: string;
  /** The declaring module, package-relative: what the feature's images resolve against. */
  module: string;
  meta: FeatureMetaSnapshot;
};

/** One part or assembly definition a package exports. */
export type PackageManifestPart = {
  exportName: string;
  module: string;
  /** The `part('…')` or `assembly('…')` name, display only; the export name when it has none. */
  name: string;
  kind: 'part' | 'assembly';
  /** `value`: inserted as `insert(name)`; `factory`: as `insert(name())`. */
  exportKind: 'value' | 'factory';
  /** The definition's `param()` interface, defaults included. */
  params: CatalogParamDef[];
};

/**
 * A package archive's `manifest.json` (research §2): what installers, the
 * catalogs, upgrades and the hub read. Generated by `fluidcad pack`; the
 * author never writes it. Identity is copied from the workspace's
 * `package` block, which stays the only place an author writes it.
 *
 * `manifestVersion` is what tells a package from an archive of the old
 * model packer, whose `manifest.json` has a `schemaVersion` instead.
 *
 * Nothing in it records when it was packed, so packing the same tree twice
 * gives the same archive and the same tree hash. Archives packed before
 * that carry a `createdAt`; readers ignore it, like any field they don't
 * know.
 */
export type PackageManifest = {
  manifestVersion: 1;
  /** The package's name, `@acme/gears` (HD30). */
  name: string;
  version: string;
  description?: string;
  license?: string;
  author?: string;
  homepage?: string;
  keywords?: string[];
  /** The engine the package was packed and checked on. */
  engine: string;
  /** The lowest engine it supports: the block's `minEngine`, else the workspace's engine pin, else {@link engine}. */
  minEngine: string;
  /** `SDK_VERSION` of the packing engine (K10). */
  sdkVersion: number;
  /** The unit every file without its own `unit()` is in. */
  unit: LengthUnit;
  /** Per-file `unit()` declarations, by package path; empty when no file declares one. */
  fileUnits: Record<string, LengthUnit>;
  /** What the package offers: `features`, `parts` (assemblies count as parts), or both. */
  contents: ('features' | 'parts')[];
  features: PackageManifestFeature[];
  parts: PackageManifestPart[];
  /** Every file of the archive except `manifest.json` itself, sorted. */
  files: string[];
};

/** One of the three folders a package keeps its modules in (HD20). */
export type PackageFolder = 'features' | 'parts' | 'assemblies';

/** A module whose suffix belongs in another of the three folders. */
export type MisplacedModule = {
  /** Workspace-relative, POSIX. */
  path: string;
  /** The folder it sits in. */
  folder: PackageFolder;
  /** The folder its suffix belongs in. */
  belongsIn: PackageFolder;
};

/** A package's manifest entries by folder, as `fluidcad pack` lists them. */
export type PackageContents = {
  features: { id: string; exportName: string; module: string }[];
  parts: { exportName: string; name: string; module: string; params: number }[];
  assemblies: { exportName: string; name: string; module: string; params: number }[];
  /** The parts and assemblies together: a package needs at least one to publish (`no-models`). */
  models: number;
  /** The author's doc pages, `docs/**\/*.md` in `files` order ({@link PackageLayout.docPagesOf}); empty for a package without `docs/`. */
  docs: string[];
};

/**
 * Where things are in a package, which is also the archive and the
 * installed directory, byte for byte.
 *
 * **The three folders (HD20).** A package keeps its feature modules in
 * `features/`, its parts in `parts/` and its assemblies in `assemblies/`,
 * nested folders and plain `.js` helpers allowed inside each. The folders
 * decide what it exports: every module in them whose suffix fits its
 * folder. Every script pack ships must live in one of them, and a module
 * whose suffix belongs in another folder is refused.
 *
 * **The root.** The three generated files sit at the root and those paths
 * are reserved: pack refuses a workspace file that would land on one.
 * README, LICENSE and CHANGELOG ship beside them.
 *
 * **`docs/` (package-docs DOC6).** An optional fourth folder that holds no
 * modules: the author's markdown pages (`.md`) and the images they show
 * (the feature image types), nested folders allowed. Pack ships all of it,
 * and readers find the pages as the `docs/**\/*.md` entries of `files`;
 * the manifest has no field of its own for them. A script there is
 * `outside-layout`, any other file type `docs-file`, and a page, an image
 * or the folder over its cap `docs-too-large` — the hub's port
 * (`api/src/format/package-layout.ts`) mirrors these rules, their codes,
 * their caps and their sentences.
 *
 * Node builtins and import-free siblings only (the type imports vanish at
 * compile time): `package-fields.ts`, which the plain-JS CLI imports
 * compiled through `project-config.ts`, names the folders from here.
 */
export class PackageLayout {
  static readonly MANIFEST_VERSION = 1 as const;
  /** Generated: identity, compatibility, contents and snapshots. */
  static readonly MANIFEST = 'manifest.json';
  /** Generated: the package entry, named re-exports of everything the package exports. */
  static readonly ENTRY = 'index.js';
  /** Generated: `{ unit, materials }` only, what the engine reads while rendering. */
  static readonly CONFIG = 'fluidcad.json';
  static readonly RESERVED: readonly string[] = [PackageLayout.MANIFEST, PackageLayout.ENTRY, PackageLayout.CONFIG];
  static readonly EXTENSION = '.fluidpkg';

  /** The three folders, in the order pack lists them. */
  static readonly FOLDERS: readonly PackageFolder[] = ['features', 'parts', 'assemblies'];

  /** The optional docs folder: markdown pages and their images, never a module (DOC6). */
  static readonly DOCS = 'docs';
  /** A doc page: a markdown file. */
  static readonly DOC_PAGE = /\.md$/i;
  /** An image a doc page shows: the types a feature's images take. */
  static readonly DOC_IMAGE = /\.(svg|png|jpe?g|webp)$/i;
  /** A script, as the layout rules read one (the hub's own test, case and all): `.js`, `.mjs` or `.cjs`. */
  static readonly SCRIPT = /\.(?:js|mjs|cjs)$/;

  /** The largest doc page: 256 KB (the hub's `docsPageBytes`). */
  static readonly DOCS_PAGE_BYTES = 256 * 1024;
  /** The largest doc image: 2 MB (the hub's `docsImageBytes`). */
  static readonly DOCS_IMAGE_BYTES = 2 * 1024 * 1024;
  /** All of `docs/` together: 4 MB (the hub's `docsBytes`). */
  static readonly DOCS_BYTES = 4 * 1024 * 1024;
  /** The most files `docs/` may hold: 200 (the hub's `docsFiles`). */
  static readonly DOCS_FILES = 200;

  /**
   * The suffix ↔ folder table: which folder each kind of module belongs in.
   * `*.fluid.js` is a part, as everywhere in FluidCAD. A script with none of
   * these suffixes is a helper, at home in any of the three.
   */
  static readonly SUFFIX_FOLDERS: readonly (readonly [suffix: string, folder: PackageFolder])[] = [
    ['.feature.js', 'features'],
    ['.part.js', 'parts'],
    ['.fluid.js', 'parts'],
    ['.assembly.js', 'assemblies'],
  ];

  /** What a module of each suffix is called in a refusal. */
  private static readonly KIND_NAMES: Record<string, { one: string; many: string }> = {
    '.feature.js': { one: 'a feature module', many: 'feature modules' },
    '.part.js': { one: 'a part', many: 'parts' },
    '.fluid.js': { one: 'a part', many: 'parts' },
    '.assembly.js': { one: 'an assembly', many: 'assemblies' },
  };

  /** Directory names the walk never enters, besides dot-entries. */
  private static readonly SKIPPED = ['node_modules'];

  /**
   * The archive's file name, `@acme/gears` 1.2.0 →
   * `acme-gears-1.2.0.fluidpkg`: what `fluidcad pack` writes, and the hub
   * download's scratch file.
   */
  static archiveName(name: string, version: string): string {
    const scope = PackageName.scope(name);
    if (scope === null) {
      throw new Error(`${JSON.stringify(name)} is not a package name: ${PackageName.RULE}.`);
    }
    return `${scope}-${PackageName.bareOf(name)}-${version}${PackageLayout.EXTENSION}`;
  }

  static isReserved(packagePath: string): boolean {
    return PackageLayout.RESERVED.includes(packagePath);
  }

  /** The folder a package path sits in (`parts/gears/spur.part.js` → `parts`), or null outside the three. */
  static folderOf(packagePath: string): PackageFolder | null {
    const slash = packagePath.indexOf('/');
    if (slash <= 0) {
      return null;
    }
    const top = packagePath.slice(0, slash);
    return (PackageLayout.FOLDERS as readonly string[]).includes(top) ? (top as PackageFolder) : null;
  }

  /** The folder a module's suffix belongs in, or null for a helper script or any other file. */
  static folderFor(packagePath: string): PackageFolder | null {
    const suffix = PackageLayout.suffixOf(packagePath);
    return suffix === null ? null : PackageLayout.SUFFIX_FOLDERS.find(([s]) => s === suffix)![1];
  }

  /** `features/`, `parts/` and `assemblies/`, for a sentence. */
  static describeFolders(folders: readonly PackageFolder[] = PackageLayout.FOLDERS): string {
    const named = folders.map((f) => `${f}/`);
    return named.length <= 1 ? (named[0] ?? '') : `${named.slice(0, -1).join(', ')} and ${named[named.length - 1]}`;
  }

  /** Which of the three folders the workspace has, in {@link FOLDERS} order. */
  static foldersIn(workspacePath: string): PackageFolder[] {
    return PackageLayout.FOLDERS.filter((folder) => {
      try {
        return fs.statSync(path.join(workspacePath, folder)).isDirectory();
      } catch {
        return false;
      }
    });
  }

  /**
   * What the package exports, workspace-relative and sorted: every
   * `*.feature.js` in `features/`, every `*.part.js` and `*.fluid.js` in
   * `parts/` and every `*.assembly.js` in `assemblies/`, nested folders
   * included. Dot-entries and `node_modules` are skipped. A module in the
   * wrong folder is not an export: {@link misplacedIn} lists it.
   */
  static exportsOf(workspacePath: string): string[] {
    return PackageLayout.modulesIn(workspacePath).filter((rel) => PackageLayout.folderFor(rel) === PackageLayout.folderOf(rel));
  }

  /** Every module in the three folders whose suffix belongs in another one, sorted. */
  static misplacedIn(workspacePath: string): MisplacedModule[] {
    const out: MisplacedModule[] = [];
    for (const rel of PackageLayout.modulesIn(workspacePath)) {
      const folder = PackageLayout.folderOf(rel)!;
      const belongsIn = PackageLayout.folderFor(rel)!;
      if (folder !== belongsIn) {
        out.push({ path: rel, folder, belongsIn });
      }
    }
    return out;
  }

  /** The `wrong-folder` sentence for a misplaced module. */
  static describeMisplaced(module: MisplacedModule): string {
    const kind = PackageLayout.KIND_NAMES[PackageLayout.suffixOf(module.path)!];
    return `${module.path} is ${kind.one} in ${module.folder}/, but ${kind.many} belong in ${module.belongsIn}/: move it there.`;
  }

  /** The `outside-layout` sentence for a script outside the three folders that nothing imports (the hub words it the same). */
  static describeOutsideLayout(packagePath: string): string {
    return `${packagePath} is outside ${PackageLayout.describeFolders()}: a package ships only what those folders hold. ` +
      `Move ${packagePath} into one of them.`;
  }

  /** Whether a package path sits in `docs/`. */
  static isDocsPath(packagePath: string): boolean {
    return packagePath.startsWith(`${PackageLayout.DOCS}/`);
  }

  static isDocPage(packagePath: string): boolean {
    return PackageLayout.isDocsPath(packagePath) && PackageLayout.DOC_PAGE.test(packagePath);
  }

  static isDocImage(packagePath: string): boolean {
    return PackageLayout.isDocsPath(packagePath) && PackageLayout.DOC_IMAGE.test(packagePath);
  }

  static isScript(packagePath: string): boolean {
    return PackageLayout.SCRIPT.test(packagePath);
  }

  /**
   * Every file under the workspace's `docs/`, workspace-relative and sorted,
   * nested folders included. Dot-entries and `node_modules` are skipped, as
   * in the three folders; empty without a `docs/` folder.
   */
  static docsIn(workspacePath: string): string[] {
    const out: string[] = [];
    PackageLayout.walk(path.join(workspacePath, PackageLayout.DOCS), PackageLayout.DOCS, out);
    return out.sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  }

  /** A manifest's doc pages: the `docs/**\/*.md` entries of `files`, in its order. A manifest from before `docs/` has none. */
  static docPagesOf(manifest: Partial<Pick<PackageManifest, 'files'>>): string[] {
    return (manifest.files ?? []).filter((file) => PackageLayout.isDocPage(file));
  }

  /** The `docs-file` sentence: a file in `docs/` that is neither a page nor an image. */
  static describeDocsFile(packagePath: string): string {
    return `${packagePath} can't ship: ${PackageLayout.DOCS}/ holds markdown pages (.md) and the images they show ` +
      `(.svg, .png, .jpg, .jpeg, .webp) only. Move it out of ${PackageLayout.DOCS}/ or remove it.`;
  }

  /** The `docs-too-large` sentence for one page or image over its cap. */
  static describeDocsFileTooLarge(packagePath: string, bytes: number): string {
    const page = PackageLayout.DOC_PAGE.test(packagePath);
    const limit = page ? PackageLayout.DOCS_PAGE_BYTES : PackageLayout.DOCS_IMAGE_BYTES;
    return `${packagePath} is ${PackageLayout.size(bytes)}; ${page ? 'a page' : 'an image'} in ${PackageLayout.DOCS}/ can be at most ` +
      `${PackageLayout.size(limit)}. ${page ? 'Split it into smaller pages.' : 'Make it smaller.'}`;
  }

  /** The `docs-too-large` sentence for the whole folder: too many files, or too many bytes. */
  static describeDocsFolderTooLarge(files: number, bytes: number): string {
    if (files > PackageLayout.DOCS_FILES) {
      return `${PackageLayout.DOCS}/ holds ${files} files; it can hold at most ${PackageLayout.DOCS_FILES}.`;
    }
    return `${PackageLayout.DOCS}/ holds ${PackageLayout.size(bytes)}; it can hold at most ${PackageLayout.size(PackageLayout.DOCS_BYTES)}.`;
  }

  /** The parts and assemblies a manifest lists: what H6's `no-models` preflight counts. */
  static modelCount(manifest: Pick<PackageManifest, 'parts'>): number {
    return manifest.parts.length;
  }

  /** A manifest's entries by folder: features, parts, assemblies, each in manifest order, and the doc pages. */
  static contentsOf(manifest: Pick<PackageManifest, 'features' | 'parts'> & Partial<Pick<PackageManifest, 'files'>>): PackageContents {
    const model = (p: PackageManifestPart) => ({
      exportName: p.exportName,
      name: p.name,
      module: p.module,
      params: p.params?.length ?? 0,
    });
    return {
      features: manifest.features.map((f) => ({ id: f.id, exportName: f.exportName, module: f.module })),
      parts: manifest.parts.filter((p) => p.kind !== 'assembly').map(model),
      assemblies: manifest.parts.filter((p) => p.kind === 'assembly').map(model),
      models: PackageLayout.modelCount(manifest),
      docs: PackageLayout.docPagesOf(manifest),
    };
  }

  /**
   * Bytes for a sentence, in the units the caps are written in: `300 KB`,
   * `2.4 MB`. Rounded up to a tenth, so a file one byte over a cap never
   * reads as the cap itself.
   */
  private static size(bytes: number): string {
    const [value, unit] = bytes >= 1024 * 1024 ? [bytes / (1024 * 1024), 'MB'] : [bytes / 1024, 'KB'];
    const tenths = Math.ceil(value * 10) / 10;
    return `${Number.isInteger(tenths) ? tenths : tenths.toFixed(1)} ${unit}`;
  }

  /** The module suffix of a path, or null. */
  private static suffixOf(packagePath: string): string | null {
    return PackageLayout.SUFFIX_FOLDERS.find(([suffix]) => packagePath.endsWith(suffix))?.[0] ?? null;
  }

  /** Every module with a suffix from the table inside the three folders, workspace-relative and sorted. */
  private static modulesIn(workspacePath: string): string[] {
    const out: string[] = [];
    for (const folder of PackageLayout.foldersIn(workspacePath)) {
      PackageLayout.walk(path.join(workspacePath, folder), folder, out);
    }
    return out.filter((rel) => PackageLayout.suffixOf(rel) !== null).sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  }

  /** Files under `dir`, as `prefix/…`. A linked file counts; a linked directory is not entered (no cycles). */
  private static walk(dir: string, prefix: string, out: string[]): void {
    let entries: fs.Dirent[];
    try {
      entries = fs.readdirSync(dir, { withFileTypes: true });
    } catch {
      return;
    }
    for (const entry of entries) {
      if (entry.name.startsWith('.') || PackageLayout.SKIPPED.includes(entry.name)) {
        continue;
      }
      const abs = path.join(dir, entry.name);
      const rel = `${prefix}/${entry.name}`;
      if (entry.isDirectory()) {
        PackageLayout.walk(abs, rel, out);
      } else if (entry.isFile()) {
        out.push(rel);
      } else if (entry.isSymbolicLink()) {
        try {
          if (fs.statSync(abs).isFile()) {
            out.push(rel);
          }
        } catch {
          // A dangling link is nothing to export.
        }
      }
    }
  }
}
