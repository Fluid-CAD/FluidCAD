import type { FeatureMetaSnapshot } from '../../../lib/dist/index.js';
import type { CatalogParamDef } from '../part-catalog/scan.ts';
import type { LengthUnit } from '../project-config.ts';
import { PackageName } from './package-name.ts';

/** One feature builder a package exports, as its manifest snapshots it. */
export type PackageManifestFeature = {
  /** The feature's id (`acme.gear`), which starts with the package's scope (K4). */
  id: string;
  /** The name `index.js` re-exports the builder by. */
  exportName: string;
  /** The declaring module, package-relative: what the feature's images resolve against. */
  module: string;
  meta: FeatureMetaSnapshot;
  /** The module, or one it imports, reaches raw OpenCascade (see `RawOcctUse`). */
  usesOcct: boolean;
};

/** One part or assembly definition a package exports. */
export type PackageManifestPart = {
  exportName: string;
  module: string;
  /** The `part('…')` or `assembly('…')` name, display only; the export name when it has none. */
  name: string;
  kind: 'part' | 'assembly';
  /** `value`: inserted as `insert(name)`; `factory`: as `insert(name())`. */
  exportKind: 'value' | 'factory';
  /** The definition's `param()` interface, defaults included. */
  params: CatalogParamDef[];
};

/**
 * A package archive's `manifest.json` (research §2): what installers, the
 * catalogs, upgrades and the hub read. Generated by `fluidcad pack`; the
 * author never writes it. Identity is copied from the workspace's
 * `package` block, which stays the only place an author writes it.
 *
 * `manifestVersion` is what tells a package from an archive of the old
 * model packer, whose `manifest.json` has a `schemaVersion` instead.
 *
 * Nothing in it records when it was packed, so packing the same tree twice
 * gives the same archive and the same tree hash. Archives packed before
 * that carry a `createdAt`; readers ignore it, like any field they don't
 * know.
 */
export type PackageManifest = {
  manifestVersion: 1;
  name: string;
  version: string;
  description?: string;
  license?: string;
  author?: string;
  homepage?: string;
  keywords?: string[];
  /** The engine the package was packed and checked on. */
  engine: string;
  /** The lowest engine it supports: the block's `minEngine`, else the workspace's engine pin, else {@link engine}. */
  minEngine: string;
  /** `SDK_VERSION` of the packing engine (K10). */
  sdkVersion: number;
  /** The unit every file without its own `unit()` is in. */
  unit: LengthUnit;
  /** Per-file `unit()` declarations, by package path; empty when no file declares one. */
  fileUnits: Record<string, LengthUnit>;
  /** What the package offers: `features`, `parts` (assemblies count as parts), or both. */
  contents: ('features' | 'parts')[];
  features: PackageManifestFeature[];
  parts: PackageManifestPart[];
  /** Every file of the archive except `manifest.json` itself, sorted. */
  files: string[];
};

/**
 * Where things are in a package archive, which is also the installed
 * directory, byte for byte. The three generated files sit at the root and
 * those paths are reserved: pack refuses a workspace file that would land
 * on one.
 */
export class PackageLayout {
  static readonly MANIFEST_VERSION = 1 as const;
  /** Generated: identity, compatibility, contents and snapshots. */
  static readonly MANIFEST = 'manifest.json';
  /** Generated: the package entry, named re-exports of everything the package exports. */
  static readonly ENTRY = 'index.js';
  /** Generated: `{ unit, materials }` only, what the engine reads while rendering. */
  static readonly CONFIG = 'fluidcad.json';
  static readonly RESERVED: readonly string[] = [PackageLayout.MANIFEST, PackageLayout.ENTRY, PackageLayout.CONFIG];
  static readonly EXTENSION = '.fluidpkg';

  /** `@acme/gears` 1.2.0 → `acme-gears-1.2.0.fluidpkg`. */
  static archiveName(name: string, version: string): string {
    const scope = PackageName.scope(name);
    if (scope === null) {
      throw new Error(`${JSON.stringify(name)} is not a package name: ${PackageName.RULE}.`);
    }
    return `${scope}-${name.slice(name.indexOf('/') + 1)}-${version}${PackageLayout.EXTENSION}`;
  }

  static isReserved(packagePath: string): boolean {
    return PackageLayout.RESERVED.includes(packagePath);
  }
}
